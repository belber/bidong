def channel_from_tid_v2(tid_v2: int | None) -> str:
    if not tid_v2:
        return ""
    name = _MAIN_TID_V2.get(tid_v2)
    if name:
        return name
    for start, end, channel in _SUB_TID_V2_RANGES:
        if start <= tid_v2 <= end:
            return channel
    return ""
